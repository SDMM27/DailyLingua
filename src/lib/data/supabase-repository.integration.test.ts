import { readFileSync } from "node:fs";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import { beforeAll, describe, expect, it } from "vitest";
import { addDays, toDateKey } from "@/lib/domain/dates";
import { LANGUAGE_CODES } from "@/lib/domain/languages";
import type { Database } from "@/lib/supabase/database.types";
import { buildMockHistory, buildMockStudyDates } from "./mock/history";
import { buildMockMission } from "./mock/mission";
import { MOCK_PREFERENCES } from "./mock/preferences";
import { buildMockVocabulary, buildMockVocabularyLists } from "./mock/vocabulary";
import { createSupabaseRepository } from "./supabase-repository";

/**
 * Integration tests against the LOCAL Supabase stack (`npm run db:start`, seeded by
 * `npm run db:reset`). They are skipped when the stack is not running or not configured,
 * and never run against a non-local URL.
 */
const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

function isLocal(value: string | undefined): value is string {
  if (!value) return false;
  try {
    return ["127.0.0.1", "localhost", "[::1]"].includes(new URL(value).hostname);
  } catch {
    return false;
  }
}

async function localStackIsUp(): Promise<boolean> {
  if (!isLocal(url) || !key) return false;
  try {
    const res = await fetch(`${url}/auth/v1/health`, { headers: { apikey: key }, signal: AbortSignal.timeout(1500) });
    return res.ok;
  } catch {
    return false;
  }
}

/** The demo account is defined once, in the seed header. */
function readDemoCredentials() {
  const seed = readFileSync("supabase/seed.sql", "utf8");
  const email = /--\s+email:\s+(\S+)/.exec(seed)?.[1];
  const password = /--\s+password:\s+(\S+)/.exec(seed)?.[1];
  if (!email || !password) throw new Error("Demo credentials not found in supabase/seed.sql");
  return { email, password };
}

/** Ids (and list ids) are generated by the database; the demo homepage of "Il Post" differs from the mock. */
function withoutVolatileFields<T>(value: T): unknown {
  return JSON.parse(JSON.stringify(value), (k, v) => (k === "id" || k === "homepage" || k === "listId" ? undefined : v));
}

const stackIsUp = await localStackIsUp();

describe.skipIf(!stackIsUp)("Supabase repository (local database, demo user)", () => {
  const today = toDateKey(new Date(), MOCK_PREFERENCES.timeZone);
  let client: SupabaseClient<Database>;
  let userId: string;
  let repo: ReturnType<typeof createSupabaseRepository>;

  beforeAll(async () => {
    client = createClient<Database>(url!, key!, { auth: { persistSession: false } });
    const { data, error } = await client.auth.signInWithPassword(readDemoCredentials());
    if (error) throw new Error(`Demo user cannot sign in (did you run \`npm run db:reset\`?): ${error.message}`);
    userId = data.user.id;
    repo = createSupabaseRepository(client, userId);

    const seeded = await repo.getMission(today);
    if (!seeded) throw new Error("The seed has no mission for today: run `npm run db:reset` again.");
  });

  it("is not the demo repository", () => {
    expect(repo.isDemo).toBe(false);
  });

  it("knows every language of the app registry", async () => {
    const { data, error } = await client.from("languages").select("code");
    expect(error).toBeNull();
    expect(data!.map((l) => l.code)).toEqual(expect.arrayContaining([...LANGUAGE_CODES]));
  });

  it("reads the preferences (ru weight 2, it weight 1)", async () => {
    expect(await repo.getPreferences()).toEqual(MOCK_PREFERENCES);
  });

  it("reads today's mission, equivalent to the demo mission", async () => {
    const mission = await repo.getMission(today);
    expect(mission).not.toBeNull();
    expect(mission!.date).toBe(today);
    expect(withoutVolatileFields(mission)).toEqual(withoutVolatileFields(buildMockMission(today)));
  });

  it("has no mission for a day without one", async () => {
    expect(await repo.getMission(addDays(today, -400))).toBeNull();
  });

  it("reads the history, equivalent to the demo history", async () => {
    const history = await repo.getHistory();
    expect(history.length).toBeGreaterThan(6);
    // Today's pending mission is not history; days are most recent first.
    expect(history.every((h) => h.date < today)).toBe(true);
    const sortedDesc = [...history].sort((a, b) => b.date.localeCompare(a.date));
    expect(history.map((h) => h.date)).toEqual(sortedDesc.map((h) => h.date));

    const summarize = (entries: typeof history) =>
      entries.map((e) => ({
        date: e.date,
        budgetMinutes: e.budgetMinutes,
        completedMinutes: e.completedMinutes,
        sessions: e.sessions.map(({ language, title, sourceName, type, score }) => ({
          language,
          title,
          sourceName,
          type,
          score,
        })),
      }));
    expect(summarize(history.slice(0, 6))).toEqual(summarize(buildMockHistory(today)));
  });

  it("reads the study dates, equivalent to the demo ones", async () => {
    const dates = await repo.getStudyDates();
    expect([...dates].sort()).toEqual([...buildMockStudyDates(today)].sort());
  });

  it("reads the vocabulary, equivalent to the demo one", async () => {
    const items = await repo.listVocabulary();
    const byTerm = (a: { term: string }, b: { term: string }) => a.term.localeCompare(b.term);
    expect(withoutVolatileFields([...items].sort(byTerm))).toEqual(
      withoutVolatileFields([...buildMockVocabulary(today)].sort(byTerm)),
    );
  });

  it("reads the vocabulary lists and which words are in them, equivalent to the demo ones", async () => {
    const lists = await repo.listVocabularyLists();
    expect(withoutVolatileFields(lists)).toEqual(withoutVolatileFields(buildMockVocabularyLists()));
    const inList = (await repo.listVocabulary()).filter((item) => item.listId === lists[0].id);
    expect(inList.map((item) => item.term).sort()).toEqual(["mettercela tutta", "prendere in giro"]);
  });

  it("returns nothing to a visitor who is not signed in (RLS)", async () => {
    const anon = createClient<Database>(url!, key!, { auth: { persistSession: false } });
    const anonRepo = createSupabaseRepository(anon, userId);
    await expect(anonRepo.listVocabulary()).rejects.toThrow(/Supabase/);
    await expect(anonRepo.getMission(today)).rejects.toThrow(/Supabase/);
  });

  it("cannot write shared content as a user (RLS)", async () => {
    const { error } = await client.from("sources").insert({ name: "Intruder", homepage_url: "https://intruder.example" });
    expect(error).not.toBeNull();
  });
});
