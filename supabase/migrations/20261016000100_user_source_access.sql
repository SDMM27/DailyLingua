-- Paid sources a user can read. A source is readable by a user when it is free, or when the user
-- declared that they have access to it (a subscription, a free metered quota...): missions then
-- may use its contents for that user only.
--
--  * user_source_access: one row per (user, source). The owner can read, insert and delete their
--    rows (checking / unchecking « J'y ai accès »); there is nothing to update. Rows of other users
--    are invisible. Deleting a source or a profile removes its rows (cascade).
--  * The declaration is a plain claim: the app never verifies it, and NO publisher credential,
--    cookie, token or subscription identifier is stored here or anywhere else, ever. The missions
--    are generated by the service role, which reads the rows to select contents.
--  * Free sources need no row: they are readable by everyone.

create table public.user_source_access (
  user_id uuid not null references public.profiles (id) on delete cascade,
  source_id uuid not null references public.sources (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, source_id)
);

create index user_source_access_source_id_idx on public.user_source_access (source_id);

alter table public.user_source_access enable row level security;

revoke all on public.user_source_access from anon, authenticated;
grant select, insert, delete on public.user_source_access to authenticated;
create policy "user_source_access: owner can read" on public.user_source_access
  for select to authenticated
  using (user_id = (select auth.uid()));
create policy "user_source_access: owner can insert" on public.user_source_access
  for insert to authenticated
  with check (user_id = (select auth.uid()));
create policy "user_source_access: owner can delete" on public.user_source_access
  for delete to authenticated
  using (user_id = (select auth.uid()));
