-- « Je n'ai pas accès »: a user who cannot read the content of a mission (paywall, region...)
-- says so, the content is never proposed to them again and its session is replaced by another
-- readable content.
--
--  * content_refusals: one row per (user, content). The owner can read and insert their rows,
--    never change or delete them (a refusal is a fact, and the rows double as a signal to fix the
--    catalogue: contents or sources that many users cannot read). The reason has one value today;
--    the check is the place to add more.
--  * missions.session_replacements: how many replacements were reserved on the mission. Capped by
--    reserve_session_replacement (3 a day by default, the mission being the day's), which also caps
--    what a user can spend on the language model through this button.
--  * mission_sessions.replacing_since: set while a replacement of that session is in progress (null
--    = not being replaced). A reservation older than p_stale_after is considered abandoned.
--  * reserve_session_replacement: called BEFORE the language model is. Under the mission's lock it
--    checks the limit and that no replacement of the session is running, then takes a slot
--    (session_replacements + 1) and marks the session. Like generation_attempts, a reserved attempt
--    counts even if the generation later fails; N parallel requests therefore cannot all reach the
--    model, only the ones that got a slot.
--  * release_session_replacement: clears the mark after a failed generation so the user can retry
--    (the slot stays consumed).
--  * replace_mission_session: swaps a reserved session for a new one in one transaction, as the
--    service role (the new session is generated by the app, like the mission itself). The old
--    session is deleted, so its progress (activities, quiz answers, saved production, writing
--    feedback) goes with it by cascade; the new one takes the same language and position.
--
-- Errors the app maps:
--   P0002  session not found or not the user's        -> not-found
--   55000  the mission is not ready                    -> failure
--   DL001  replacement limit reached (message 'replacement_limit'), a custom SQLSTATE so that it
--          cannot be confused with a generic P0001 raise_exception -> "limit"
--   DL002  a replacement of this session is already running (message 'replacement_in_progress')
--          -> "in-progress"
--   55000  also: replace_mission_session on a session that was not reserved

create table public.content_refusals (
  user_id uuid not null references public.profiles (id) on delete cascade,
  content_id uuid not null references public.contents (id) on delete cascade,
  reason text not null default 'no_access' check (reason in ('no_access')),
  created_at timestamptz not null default now(),
  primary key (user_id, content_id)
);

create index content_refusals_content_id_idx on public.content_refusals (content_id);

alter table public.content_refusals enable row level security;

revoke all on public.content_refusals from anon, authenticated;
grant select, insert on public.content_refusals to authenticated;
create policy "content_refusals: owner can read" on public.content_refusals
  for select to authenticated
  using (user_id = (select auth.uid()));
create policy "content_refusals: owner can insert" on public.content_refusals
  for insert to authenticated
  with check (user_id = (select auth.uid()));

alter table public.missions
  add column session_replacements smallint not null default 0 check (session_replacements between 0 and 20);

-- p_session: one item of complete_mission_generation's p_sessions (language, contentId, questions,
--            expressions, production, activities[{ kind, title, estimatedMinutes }]).
-- p_meta:    generation trace of the new session; appended to generation_meta -> 'replacements'
--            (the mission's own trace, read by the app, is left as it is).
alter table public.mission_sessions add column replacing_since timestamptz;

create function public.reserve_session_replacement(
  p_session_id uuid,
  p_user_id uuid,
  p_max_per_day integer default 3,
  p_stale_after interval default interval '3 minutes'
) returns void
language plpgsql
set search_path = ''
as $$
declare
  m public.missions;
  s public.mission_sessions;
  v_mission_id uuid;
begin
  select ms.mission_id into v_mission_id
  from public.mission_sessions ms
  where ms.id = p_session_id and ms.user_id = p_user_id;
  if not found then
    raise exception 'session % not found', p_session_id using errcode = 'P0002';
  end if;

  -- Serialises concurrent reservations on the same mission; the session is re-read once the lock is held.
  select * into m from public.missions where id = v_mission_id for update;
  select * into s from public.mission_sessions where id = p_session_id and user_id = p_user_id;
  if not found then
    raise exception 'session % not found', p_session_id using errcode = 'P0002';
  end if;

  if m.status <> 'ready' then
    raise exception 'mission % is not ready (status %)', m.id, m.status using errcode = '55000';
  end if;
  if s.replacing_since is not null and s.replacing_since > now() - p_stale_after then
    raise exception 'replacement_in_progress' using errcode = 'DL002';
  end if;
  if m.session_replacements >= p_max_per_day then
    raise exception 'replacement_limit' using errcode = 'DL001';
  end if;

  update public.mission_sessions set replacing_since = now() where id = s.id;
  update public.missions set session_replacements = session_replacements + 1 where id = m.id;
end;
$$;

revoke execute on function public.reserve_session_replacement(uuid, uuid, integer, interval)
  from public, anon, authenticated;
grant execute on function public.reserve_session_replacement(uuid, uuid, integer, interval) to service_role;

create function public.release_session_replacement(p_session_id uuid) returns void
language sql
set search_path = ''
as $$
  update public.mission_sessions set replacing_since = null where id = p_session_id;
$$;

revoke execute on function public.release_session_replacement(uuid) from public, anon, authenticated;
grant execute on function public.release_session_replacement(uuid) to service_role;

create function public.replace_mission_session(
  p_session_id uuid,
  p_user_id uuid,
  p_session jsonb,
  p_meta jsonb
) returns void
language plpgsql
set search_path = ''
as $$
declare
  m public.missions;
  old public.mission_sessions;
  a jsonb;
  a_position integer := 0;
  v_session_id uuid;
begin
  select ms.* into old
  from public.mission_sessions ms
  where ms.id = p_session_id and ms.user_id = p_user_id;
  if not found then
    raise exception 'session % not found', p_session_id using errcode = 'P0002';
  end if;

  -- Serialises concurrent replacements on the same mission; re-checked once the lock is held.
  select * into m from public.missions where id = old.mission_id for update;
  select * into old from public.mission_sessions where id = p_session_id;
  if not found then
    raise exception 'session % not found', p_session_id using errcode = 'P0002';
  end if;

  if m.status <> 'ready' then
    raise exception 'mission % is not ready (status %)', m.id, m.status using errcode = '55000';
  end if;
  if old.replacing_since is null then
    raise exception 'session % is not reserved', p_session_id using errcode = '55000';
  end if;
  if jsonb_typeof(p_session) is distinct from 'object' or jsonb_typeof(p_meta) is distinct from 'object' then
    raise exception 'session and meta must be objects' using errcode = '23514';
  end if;
  if p_session ->> 'language' is distinct from old.language then
    raise exception 'the new session must keep the language %', old.language using errcode = '23514';
  end if;
  if jsonb_typeof(p_session -> 'activities') is distinct from 'array'
     or jsonb_array_length(p_session -> 'activities') = 0 then
    raise exception 'the new session has no activity' using errcode = '23514';
  end if;

  delete from public.mission_sessions where id = old.id;

  insert into public.mission_sessions (
    mission_id, user_id, position, language, content_id, questions, expressions, production
  ) values (
    m.id, m.user_id, old.position, old.language, (p_session ->> 'contentId')::uuid,
    coalesce(p_session -> 'questions', '[]'), coalesce(p_session -> 'expressions', '[]'), p_session -> 'production'
  )
  returning id into v_session_id;

  for a in select value from jsonb_array_elements(p_session -> 'activities') loop
    insert into public.mission_activities (session_id, user_id, position, kind, title, estimated_minutes)
    values (v_session_id, m.user_id, a_position, a ->> 'kind', a ->> 'title', (a ->> 'estimatedMinutes')::smallint);
    a_position := a_position + 1;
  end loop;

  -- The new session has nothing done yet: a mission that was complete is not any more.
  update public.missions
  set completed_at = null,
      generation_meta = jsonb_set(
        generation_meta, '{replacements}',
        coalesce(generation_meta -> 'replacements', '[]'::jsonb) || jsonb_build_array(p_meta)
      )
  where id = m.id;
end;
$$;

revoke execute on function public.replace_mission_session(uuid, uuid, jsonb, jsonb)
  from public, anon, authenticated;
grant execute on function public.replace_mission_session(uuid, uuid, jsonb, jsonb) to service_role;
